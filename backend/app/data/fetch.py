def _client(timeout: int) -> httpx.Client:
    return httpx.Client(
        timeout=timeout,
        headers={"User-Agent": USER_AGENT},
        follow_redirects=True,
    )


def fetch_associations_from_fifa() -> list[dict]:
    """Parse the official FIFA associations page and return raw country entries.

    The page embeds a JSON island (`countryListProps`) with 211 entries:
    name, confederation, flag (src), url (contains the FIFA code).
    """
    settings = get_settings()
    url = SOURCES["fifa-associations"].url
    with _client(settings.update_timeout_seconds) as client:
        response = client.get(url)
        response.raise_for_status()
    html = response.text

    scripts = re.findall(r"<script[^>]*>(.*?)</script>", html, re.S)
    for script in scripts:
        stripped = script.strip()
        if not stripped.startswith("{"):
            continue
        if "countryListProps" not in stripped:
            continue
        data = json.loads(stripped)
        content = data.get("props", {}).get("pageProps", {}).get("pageData", {}).get("content", [])
        for block in content:
            props = block.get("countryListProps")
            if isinstance(props, list):
                return props
    raise RuntimeError("countryListProps not found in FIFA page")


def records_from_fifa_payload(entries: list[dict], retrieved_at: datetime) -> list[AssociationRecord]:
    """Convert raw FIFA entries into AssociationRecords (with Italian names)."""
    records: list[AssociationRecord] = []
    for entry in entries:
        code = entry.get("url", "").rsplit("/", 1)[-1]
        flag = entry.get("flag", {})
        records.append(
            to_record(
                fifa_code=code,
                name=entry["name"],
                confederation=entry["confederation"],
                flag_url=flag.get("src", ""),
                source="fifa-associations",
                retrieved_at=retrieved_at,
            )
        )
    return records


def download_flag_from_bandiere_mondo(fifa_code: str) -> Optional[bytes]:
    """Fetch a flag via bandiere-mondo.it's CDN (flagcdn.com).

    Returns the raw PNG bytes on success, None on failure.
    """
    iso = FIFA_TO_FLAGCDN.get(fifa_code)
    if iso is None:
        logger.warning("No flagcdn mapping for %s", fifa_code)
        return None
    url = FLAGCDN_FLAG_URL.format(iso=iso)
    settings = get_settings()
    try:
        with _client(settings.update_timeout_seconds) as client:
            response = client.get(url)
            response.raise_for_status()
        return response.content if response.content else None
    except httpx.HTTPError as exc:  # pragma: no cover - exercised via integration test
        logger.warning("Failed to download flag for %s via bandiere-mondo.it: %s", fifa_code, exc)
        return None


def download_flag_asset(fifa_code: str, destination_dir) -> Optional[str]:
    """Download one official FIFA flag PNG into the cache dir.

    Falls back to bandiere-mondo.it (flagcdn.com) when the official FIFA
    asset API is unreachable. Returns the relative path on success, None on
    failure.
    """
    settings = get_settings()
    destination_dir.mkdir(parents=True, exist_ok=True)
    url = SOURCES["fifa-flag-assets"].url.format(CODE=fifa_code)
    try:
        with _client(settings.update_timeout_seconds) as client:
            response = client.get(url)
            response.raise_for_status()
        content = response.content
        if not content:
            logger.warning("Empty flag asset for %s", fifa_code)
            return None
    except httpx.HTTPError as exc:  # pragma: no cover - exercised via integration test
        logger.warning("FIFA flag API failed for %s (%s); trying bandiere-mondo.it", fifa_code, exc)
        content = download_flag_from_bandiere_mondo(fifa_code)
        if content is None:
            return None
    target = destination_dir / f"{fifa_code}.png"
    target.write_bytes(content)
    return str(target)
